import type { IconMetadata } from "../lib/upload/meta";
/** Optional ownership claims are entered explicitly, not inferred from artwork. */
export default function UploadMetaRights({ id, metadata, onEdit }: {
  id: string; metadata: IconMetadata; onEdit: (patch: Partial<IconMetadata>) => void;
}) {
  return <>
    {(["creator", "copyright"] as const).map((field) => <label key={field} className="svg-field up-meta-field">
      <span className="svg-label">{field === "creator" ? "Creator" : "Copyright"} (optional)</span>
      <input type="text" className="svg-input" data-testid={`upload-meta-${field}-${id}`}
        value={metadata[field] ?? ""} onChange={(event) => onEdit({ [field]: event.target.value })} />
      <small className="up-hint">Only enter your own authorized identity or rights statement. Not generated by AI.</small>
    </label>)}
  </>;
}
